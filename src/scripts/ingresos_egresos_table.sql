-- Un registro por ingreso o egreso. Los datos personales conservan su valor al registrar el movimiento.
CREATE TABLE IF NOT EXISTS ingresos_egresos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    tipo_movimiento ENUM('INGRESO', 'EGRESO') NOT NULL,
    motivo VARCHAR(100) NOT NULL,
    descripcion TEXT NULL,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    patente VARCHAR(20) NULL,
    empresa VARCHAR(255) NULL,
    empresa_ingreso_id INT NULL,
    INDEX idx_empresa_ingreso (empresa_ingreso_id),
    CONSTRAINT fk_empresa_ingreso FOREIGN KEY (empresa_ingreso_id) REFERENCES empresas_ingresos (id),
    fecha_movimiento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ingreso_id INT NULL,
    orden_venta_id INT NULL,
    archivo_jpg VARCHAR(255) NULL,
    personal_id INT NULL,
    auto VARCHAR(100) NULL,
    cargo VARCHAR(100) NULL,
    turno VARCHAR(100) NULL,
    INDEX idx_movimiento_personal (personal_id),
    CONSTRAINT fk_movimiento_personal FOREIGN KEY (personal_id) REFERENCES personal (id),
    INDEX idx_ingresos_orden_venta (orden_venta_id),
    UNIQUE KEY uq_ingresos_egresos_ingreso (ingreso_id),
    CONSTRAINT fk_ingresos_egresos_ingreso FOREIGN KEY (ingreso_id) REFERENCES ingresos_egresos (id),
    INDEX idx_fecha_movimiento (fecha_movimiento),
    INDEX idx_patente (patente)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
